-- Миграция 009: правило бесплатной отмены в настройках студии.
--
-- Зачем: личный кабинет клиента должен предупреждать об отмене «в последний
-- момент». Сколько часов до визита ещё можно отменить без последствий —
-- настройка студии, а не константа во фронтенде: владелец может её менять,
-- а текст правил на странице кабинета собирается из этого значения.
--
-- Технически:
--  * studio_info.free_cancel_hours — целое число часов (0 — бесплатной отмены
--    нет, отменять можно в любой момент, но правило всё равно показывается).
--  * DEFAULT 12 — миграция неинвазивна: у существующей студии и у сида
--    появляется то же значение, что было согласовано по умолчанию.

ALTER TABLE studio_info ADD COLUMN free_cancel_hours INTEGER NOT NULL DEFAULT 12
  CHECK (free_cancel_hours >= 0 AND free_cancel_hours <= 168);

UPDATE studio_info SET free_cancel_hours = 12 WHERE free_cancel_hours IS NULL;
